create sequence if not exists public.report_number_seq;

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  report_number text unique not null,
  report_type text not null,
  report_name text not null,
  department text not null check (
    department in ('Produksi', 'Gudang', 'Operasional', 'Absensi')
  ),
  report_date date not null,
  submitted_by text not null,
  status text not null check (
    status in (
      'draft',
      'submitted',
      'under_review',
      'revision_requested',
      'approved',
      'collected'
    )
  ),
  created_at timestamptz not null default now(),
  notes text
);

create table if not exists public.thread_usage_entries (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.reports(id) on delete cascade,
  machine_number integer not null check (machine_number between 1 and 11),
  opening_stock integer not null check (opening_stock >= 0),
  added integer not null check (added >= 0),
  used integer not null check (used >= 0),
  remaining integer generated always as (opening_stock + added - used) stored,
  unique (report_id, machine_number),
  check (opening_stock + added >= used)
);

create table if not exists public.waste_material_items (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.reports(id) on delete cascade,
  item_name text not null,
  weight_kg numeric(12, 2) not null check (weight_kg > 0),
  quantity numeric(12, 2) not null check (quantity > 0),
  quantity_unit text not null check (quantity_unit in ('kg', 'bal'))
);

create index if not exists reports_created_at_idx
  on public.reports (created_at desc);
create index if not exists reports_filters_idx
  on public.reports (report_type, department, status, report_date);
create index if not exists thread_usage_report_id_idx
  on public.thread_usage_entries (report_id);
create index if not exists waste_material_report_id_idx
  on public.waste_material_items (report_id);

create or replace function public.assign_report_number()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
  department_code text;
  sequence_number text;
begin
  department_code := case new.department
    when 'Produksi' then 'PRD'
    when 'Gudang' then 'GDG'
    when 'Operasional' then 'OPS'
    when 'Absensi' then 'ABS'
  end;
  sequence_number := nextval('public.report_number_seq')::text;
  new.report_number := department_code || '-' ||
    to_char(new.report_date, 'YYYYMMDD') || '-' ||
    lpad(sequence_number, greatest(4, length(sequence_number)), '0');
  return new;
end;
$$;

drop trigger if exists reports_assign_report_number on public.reports;
create trigger reports_assign_report_number
before insert on public.reports
for each row execute function public.assign_report_number();

create or replace function public.create_thread_usage_report(
  p_report_date date,
  p_submitted_by text,
  p_status text,
  p_entries jsonb
)
returns bigint
language plpgsql
set search_path = public, pg_temp
as $$
declare
  new_report_id bigint;
begin
  insert into public.reports (
    report_number, report_type, report_name, department,
    report_date, submitted_by, status
  )
  values (
    '', 'pemakaian-benang', 'Pemakaian Benang', 'Gudang',
    p_report_date, p_submitted_by, p_status
  )
  returning id into new_report_id;

  insert into public.thread_usage_entries (
    report_id, machine_number, opening_stock, added, used
  )
  select
    new_report_id, entry.machine_number, entry.opening_stock, entry.added, entry.used
  from jsonb_to_recordset(p_entries) as entry(
    machine_number integer,
    opening_stock integer,
    added integer,
    used integer
  );

  return new_report_id;
end;
$$;

create or replace function public.create_waste_material_report(
  p_report_date date,
  p_submitted_by text,
  p_department text,
  p_status text,
  p_notes text,
  p_materials jsonb
)
returns bigint
language plpgsql
set search_path = public, pg_temp
as $$
declare
  new_report_id bigint;
begin
  insert into public.reports (
    report_number, report_type, report_name, department,
    report_date, submitted_by, status, notes
  )
  values (
    '', 'laporan-plastik-kardus-bekas',
    'Laporan Harian Plastik/Kardus Bekas', p_department,
    p_report_date, p_submitted_by, p_status, p_notes
  )
  returning id into new_report_id;

  insert into public.waste_material_items (
    report_id, item_name, weight_kg, quantity, quantity_unit
  )
  select
    new_report_id, material.item_name, material.weight_kg,
    material.quantity, material.quantity_unit
  from jsonb_to_recordset(p_materials) as material(
    item_name text,
    weight_kg numeric,
    quantity numeric,
    quantity_unit text
  );

  return new_report_id;
end;
$$;

